"""Curated free data sources for overlays and live layers.

Every source is added as a normal Strata layer. URLs are deliberately kept in
one place so the catalogue can be reviewed, tested and extended without
duplicating request logic in the API or frontend.
"""

from __future__ import annotations

from typing import Any


def _xyz(
    source_id: str,
    label: str,
    url: str,
    description: str,
    attribution: str,
    licence: str,
    category: str,
    maxzoom: int = 19,
    minzoom: int = 0,
    tile_size: int = 256,
) -> dict[str, Any]:
    return {
        "id": source_id,
        "label": label,
        "provider": "xyz",
        "description": description,
        "attribution": attribution,
        "licence": licence,
        "category": category,
        "config": {
            "url_template": url,
            "tile_size": tile_size,
            "minzoom": minzoom,
            "maxzoom": maxzoom,
            "scheme": "xyz",
        },
    }


def _wms(
    source_id: str,
    label: str,
    url: str,
    layers: str,
    description: str,
    attribution: str,
    licence: str,
    category: str,
    image_format: str = "image/png",
    transparent: bool = True,
) -> dict[str, Any]:
    return {
        "id": source_id,
        "label": label,
        "provider": "wms",
        "description": description,
        "attribution": attribution,
        "licence": licence,
        "category": category,
        "config": {
            "url": url,
            "layers": layers,
            "version": "1.3.0",
            "format": image_format,
            "transparent": transparent,
        },
    }


